#1.For Loops

name = "Mamata"
for i in name:
    print(i)
    if(i == "t"):
        print("This is something special")

colors = ["Red","Yellow","Pink","Blue","Marron"]
for color in colors:
    print(color)
    for i in color:
        print(i)

fruits = ["Banana","Apple","orange","Mango","Grapes"]
for fruit in fruits:
    print(fruit) 
    for i in fruit:
        print(i)       
